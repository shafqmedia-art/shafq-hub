import asyncio,json,urllib.request
from playwright.async_api import async_playwright
U='http://localhost:8770/index.html'; R=[]
def ok(n,c,e=''): R.append(c); print(('PASS ' if c else 'FAIL ')+n,'' if c else e)
def notes(): return json.load(urllib.request.urlopen('http://localhost:8770/__notify'))
async def fm(page,vals):
    for k,v in vals.items():
        el=page.locator(f'#m_{k}')
        if await el.evaluate('e=>e.tagName')=='SELECT': await el.select_option(v)
        else: await el.fill(v)
    await page.locator('#modal button[type=submit]').click(); await page.wait_for_timeout(900)
async def main():
    async with async_playwright() as p:
        b=await p.chromium.launch(executable_path='/usr/bin/google-chrome',args=['--no-sandbox'])
        ctx=await b.new_context(viewport={'width':1300,'height':900},service_workers='allow')
        page=await ctx.new_page(); errs=[]; page.on('pageerror',lambda e:errs.append(str(e))); page.on('dialog',lambda d:asyncio.ensure_future(d.accept()))
        await page.goto(U); await page.wait_for_timeout(1200)
        await page.fill('#s_name','عبد الرحمن'); await page.fill('#s_phone','0952000000'); await page.fill('#s_pass','secret12'); await page.click('form[data-form=setup] button'); await page.wait_for_timeout(1800)
        ok('push banner on dashboard',await page.locator('.pushbar [data-act=pushOn]').count()==1)
        await page.click('.pushbar [data-act=pushLater]'); await page.wait_for_timeout(300)
        ok('later hides banner',await page.locator('.pushbar').count()==0)
        await page.goto(U+'#/team'); await page.wait_for_timeout(400)
        await page.click('[data-act=addMember]'); await fm(page,{'name':'سارة','gender':'f','phone':'0933333333','pass':'12345678'})
        sid=await page.evaluate("SHAFQ.db().users.filter(u=>u.name=='سارة')[0].id")
        await page.goto(U+'#/tasks'); await page.wait_for_timeout(400)
        await page.click('[data-act=addTask]'); await fm(page,{'title':'مونتاج ريل','user_id':sid})
        n=notes(); ok('task notify to member',any(i['to']==[sid] and 'مهمة جديدة' in i['title'] for x in n for i in x['items']),json.dumps(n,ensure_ascii=False)[:300])
        await page.goto(U+'#/clients'); await page.wait_for_timeout(300)
        await page.click('[data-act=addClient]'); await fm(page,{'name':'الخباز','value':'500','months':'3'})
        cid=await page.evaluate('SHAFQ.db().clients[0].id')
        await page.goto(U+'#/client/'+cid); await page.wait_for_timeout(400)
        await page.click('[data-act=addMove]'); await fm(page,{'amount':'300','service':'تصوير'})
        n=notes(); ok('payment notify to client',any(i['to']=={'client':cid} and 'دفعتكم' in i['title'] and 'تصوير' in i['body'] for x in n for i in x['items']))
        await page.goto(U+'#/finance'); await page.wait_for_timeout(300)
        await page.click('.acts [data-act=addMove]'); await fm(page,{'dir':'out','cat':'أجر فريق','amount':'50','user_id':sid})
        n=notes(); ok('payout notify feminine',any(i['to']==[sid] and 'إلكِ' in i['title'] for x in n for i in x['items']))
        await page.goto(U+'#/m/content'); await page.wait_for_timeout(400)
        await page.click('[data-act=addItem]'); await fm(page,{'name':'افتتاح الفرع','client_id':cid})
        await page.locator('details.tile').evaluate_all('es=>es.forEach(e=>e.open=true)')
        await page.locator('[data-chg=istatus]').first.select_option('منشور'); await page.wait_for_timeout(900)
        n=notes(); ok('post published notify client',any(i['to']=={'client':cid} and 'منشور' in i['title'] for x in n for i in x['items']))
        await page.goto(U+'#/profile'); await page.wait_for_timeout(400)
        ok('profile push tile',await page.locator('text=الإشعارات').count()>=1)
        await page.click('[data-act=logout]'); await page.wait_for_timeout(1200)
        await page.fill('#l_phone','0933333333'); await page.fill('#l_pass','12345678'); await page.click('form[data-form=login] button'); await page.wait_for_timeout(2000)
        ok('banner for member (later was today, so hidden)',await page.locator('.pushbar').count()==0)
        await page.locator('details.tile').evaluate_all('es=>es.forEach(e=>e.open=true)')
        await page.locator('[data-chg=task]').first.check(); await page.wait_for_timeout(1000)
        n=notes(); ok('member done notify managers',any(i['to']=='managers' and 'أنجزت سارة' in i['title'] for x in n for i in x['items']))
        # grant + try enable (push service unreachable offline -> graceful)
        await ctx.grant_permissions(['notifications'],origin='http://localhost:8770')
        await page.evaluate("localStorage.removeItem('shafq_push_later')")
        await page.goto(U+'#/profile'); await page.wait_for_timeout(800)
        await page.locator('details.tile').evaluate_all('es=>es.forEach(e=>e.open=true)')
        t=await page.locator('main, #app').first.inner_text()
        ok('granted state shows test button',await page.locator('[data-act=pushTest]').count()==1, t[-300:])
        ok('no js errors',not errs,str(errs))
        await b.close()
asyncio.run(main()); print('%d/%d'%(sum(R),len(R)))
